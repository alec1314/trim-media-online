#!/usr/bin/env python3
"""弹幕：对接 danmu_api（弹弹play 兼容接口），把弹幕转成 ASS 字幕轨。

飞牛播放器没有弹幕渲染层，但 Web 端播放器内置 JASSUB（libass）外挂字幕渲染，
支持 ASS 的 \\move 动画。因此这里把弹幕生成 ASS，作为一条名为「弹幕」的外挂
字幕注入 stream 响应；播放器选择该字幕后会请求
GET /v/api/v1/subtitle/dl/<guid>，由 app.py 转给本模块返回 ASS 文本。

不内置、不代理任何弹幕服务：接口地址由使用者自行部署 danmu_api 后填写。
"""
from __future__ import annotations

import asyncio
import hashlib
import json
import re
import time
from pathlib import Path

import httpx

from config import config
from store import store
import inject

_STATE = Path(__file__).resolve().parent.parent / "state" / "danmu_bind.json"

_PREFIX = "dm"
_GUID_LEN = 32
_TTL = 6 * 3600
_NEG_TTL = 10 * 60
_MAX_BIND = 1000
_MAX_CACHE = 200

_BIND: dict[str, dict] = {}
_ASS: dict[str, tuple[float, str]] = {}
_MATCH: dict[str, tuple[float, int | None]] = {}
_LOCK = asyncio.Lock()

_ASS_HEADER = """[Script Info]
; Generated by trim-media-online
ScriptType: v4.00+
PlayResX: 1920
PlayResY: 1080
WrapStyle: 2
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Danmu,go noto current,48,&H00FFFFFF,&H00FFFFFF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,2,0,7,20,20,20,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

_S = 1920.0
_H = 1080.0
_FONT = 48
_SCROLL_DUR = 8.0
_FIXED_DUR = 4.5
_SCROLL_LANES = 12
_FIXED_LANES = 4
_LANE_H = 58
_TOP_Y = 72
_BOTTOM_Y = _H - 90


def _load() -> None:
    try:
        raw = json.loads(_STATE.read_text())
    except Exception:
        return
    if isinstance(raw, dict):
        for guid, ent in raw.items():
            if isinstance(ent, dict) and ent.get("mg"):
                _BIND[str(guid)] = ent


def _save() -> None:
    try:
        _STATE.parent.mkdir(parents=True, exist_ok=True)
        if len(_BIND) > _MAX_BIND:
            keep = sorted(_BIND.items(), key=lambda kv: kv[1].get("at", 0))[-_MAX_BIND:]
            _BIND.clear()
            _BIND.update(dict(keep))
        tmp = _STATE.with_suffix(".tmp")
        tmp.write_text(json.dumps(_BIND, ensure_ascii=False, separators=(",", ":")))
        tmp.replace(_STATE)
    except Exception:
        pass


_load()


def api_base(api: str | None = None, token: str | None = None) -> str:
    cfg = config.get()
    raw = str(cfg.get("danmu_api") if api is None else api).strip().rstrip("/")
    if not raw:
        return ""
    if not re.match(r"^https?://", raw, re.I):
        raw = "http://" + raw
    tok = str(cfg.get("danmu_token") if token is None else token).strip().strip("/")
    # danmu_api 默认 token 87654321 可直接省略；自定义 token 走 /{TOKEN}/api/v2/...
    if tok and tok != "87654321" and raw.rsplit("/", 1)[-1] != tok:
        raw = f"{raw}/{tok}"
    return raw


def enabled() -> bool:
    cfg = config.get()
    return bool(cfg.get("danmu_enabled")) and bool(api_base())


def _client(timeout: float = 12.0) -> httpx.AsyncClient:
    return httpx.AsyncClient(
        timeout=httpx.Timeout(timeout, connect=5.0),
        trust_env=False,
        follow_redirects=True,
        headers={"User-Agent": "trim-media-online/danmu"},
    )


def _stream_guid(mg: str, og: str) -> str:
    cfg = config.get()
    raw = "|".join([
        "v1", mg or "", og or "", api_base(),
        str(cfg.get("danmu_offset") or 0),
        str(cfg.get("danmu_limit") or 800),
    ])
    return _PREFIX + hashlib.md5(raw.encode("utf-8")).hexdigest()[: _GUID_LEN - len(_PREFIX)]


def make_stream(mg: str, og: str, title: str, year: str = "",
                cat: str = "tv", duration: int = 0,
                auto: bool | None = None,
                ep_title: str = "") -> dict | None:
    """为一条在线播放链生成「弹幕」字幕轨；未启用/未配置接口时返回 None。"""
    if not enabled() or not mg:
        return None
    cfg = config.get()
    guid = _stream_guid(mg, og)
    if guid not in _BIND:
        _BIND[guid] = {
            "mg": mg, "og": og or "", "title": title or "",
            "year": str(year or ""), "cat": cat or "tv",
            "dur": int(duration or 0), "ep_title": ep_title or "",
            "at": time.time(),
        }
        _save()
    if auto is None:
        auto = bool(cfg.get("danmu_auto", True))
    return {
        "guid": guid,
        "media_guid": mg,
        "title": "弹幕",
        "language": "chi",
        "codec_name": "ass",
        "codec_type": "subtitle",
        "format": "ass",
        "index": 0,
        "is_default": 1 if auto else 0,
        "is_external": 1,
        "is_bitmap": 0,
        "extra_file": 1,
        "forced": 0,
        "status": 1,
        "ext1": 0,
        "disabled": 0,
    }


def is_danmu_guid(guid: str) -> bool:
    return guid in _BIND


def _text_width(text: str, fs: float = _FONT) -> float:
    w = 0.0
    for ch in text:
        w += fs if ord(ch) > 0x2E7F else fs * 0.56
    return w


def _ts(sec: float) -> str:
    sec = max(0.0, float(sec))
    h = int(sec // 3600)
    m = int(sec % 3600 // 60)
    s = sec % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def _colour(value: int) -> str:
    v = max(0, min(0xFFFFFF, int(value or 0)))
    r = (v >> 16) & 0xFF
    g = (v >> 8) & 0xFF
    b = v & 0xFF
    return f"&H00{b:02X}{g:02X}{r:02X}&"


def _clean_text(text: str) -> str:
    text = str(text or "").replace("\r", " ").replace("\n", " ")
    text = text.replace("{", "｛").replace("}", "｝").replace("\\", "＼")
    return "".join(ch for ch in text if ch >= " " or ch == "\t").strip()


def _parse_comment(item: dict) -> tuple[float, int, int, str] | None:
    if not isinstance(item, dict):
        return None
    p = item.get("p")
    if isinstance(p, str):
        parts = p.split(",")
    elif isinstance(p, (list, tuple)):
        parts = list(p)
    else:
        return None
    if len(parts) < 1:
        return None
    try:
        t = float(parts[0])
        mode = int(parts[1]) if len(parts) > 1 else 1
        # p = 时间,类型,字号,颜色,...（颜色是第 4 段，不是第 3 段）
        colour = (int(parts[3]) if len(parts) > 3
                  else (int(parts[2]) if len(parts) > 2 else 0xFFFFFF))
    except (TypeError, ValueError):
        return None
    text = _clean_text(item.get("m") or "")
    if not text or len(text) > 120:
        return None
    return t, mode, colour, text


def _build_ass(comments: list, offset: float = 0.0, limit: int = 800,
               duration: int = 0) -> str:
    """弹幕 JSON -> ASS：滚动/顶部/底部，含简单防重叠车道分配。"""
    rows: list[tuple[float, int, int, str]] = []
    seen: set[tuple[int, str]] = set()
    for c in comments or []:
        parsed = _parse_comment(c)
        if not parsed:
            continue
        t, mode, colour, text = parsed
        t += float(offset or 0)
        if t < 0 or (duration and t > duration + 5):
            continue
        key = (int(t * 2), text)
        if key in seen:
            continue
        seen.add(key)
        rows.append((t, mode, colour, text))
    if not rows:
        return _ASS_HEADER

    rows.sort(key=lambda x: x[0])
    limit = max(50, int(limit or 800))
    if len(rows) > limit:
        step = len(rows) / float(limit)
        rows = [rows[min(len(rows) - 1, int(i * step))] for i in range(limit)]

    lanes: list[tuple[float, float, float] | None] = [None] * _SCROLL_LANES
    top_free = [0.0] * _FIXED_LANES
    bottom_free = [0.0] * _FIXED_LANES
    out: list[str] = []

    def pick_fixed(t: float, free: list[float]) -> int | None:
        for i, until in enumerate(free):
            if t >= until:
                free[i] = t + _FIXED_DUR
                return i
        return None

    for t, mode, colour, text in rows:
        if mode == 5:  # 顶部
            lane = pick_fixed(t, top_free)
            if lane is None:
                continue
            y = _TOP_Y + lane * _LANE_H
            body = (f"{{\\an8\\pos({_S / 2:.0f},{y:.0f})\\fs{_FONT}"
                    f"\\c{_colour(colour)}}}")
            out.append(f"Dialogue: 0,{_ts(t)},{_ts(t + _FIXED_DUR)},Danmu,,0,0,0,,"
                       f"{body}{text}")
            continue
        if mode == 4:  # 底部
            lane = pick_fixed(t, bottom_free)
            if lane is None:
                continue
            y = _BOTTOM_Y - lane * _LANE_H
            body = (f"{{\\an2\\pos({_S / 2:.0f},{y:.0f})\\fs{_FONT}"
                    f"\\c{_colour(colour)}}}")
            out.append(f"Dialogue: 0,{_ts(t)},{_ts(t + _FIXED_DUR)},Danmu,,0,0,0,,"
                       f"{body}{text}")
            continue

        width = _text_width(text)
        lane = next((i for i, st in enumerate(lanes) if st is None), None)
        if lane is None:
            candidates = []
            for i, st in enumerate(lanes):
                t0, w0, d0 = st
                cleared = (t - t0) >= d0 * 24.0 / (_S + w0)
                speed_new = (_S + width) / _SCROLL_DUR
                speed_old = (_S + w0) / max(d0, 0.1)
                if cleared and (speed_new <= speed_old + 1e-6
                                or (t - t0) >= d0 * 0.92):
                    candidates.append((i, t0))
            if candidates:
                lane = min(candidates, key=lambda x: x[1])[0]
            else:
                # 极密集时退化为最空闲车道，允许轻微重叠，避免整批丢弃
                lane = max(range(len(lanes)),
                           key=lambda i: (t - lanes[i][0]) / max(lanes[i][2], 0.1))
        lanes[lane] = (t, width, _SCROLL_DUR)
        y = _TOP_Y + lane * _LANE_H
        x1 = _S + 10
        x2 = -width - 10
        body = (f"{{\\an4\\move({x1:.0f},{y:.0f},{x2:.0f},{y:.0f})\\fs{_FONT}"
                f"\\c{_colour(colour)}}}")
        out.append(f"Dialogue: 0,{_ts(t)},{_ts(t + _SCROLL_DUR)},Danmu,,0,0,0,,"
                   f"{body}{text}")

    return _ASS_HEADER + "\n".join(out) + ("\n" if out else "")


async def _match(base: str, name: str, timeout: float = 10.0) -> dict | None:
    async with _client(timeout) as cli:
        r = await cli.post(f"{base}/api/v2/match", json={"fileName": name})
        if r.status_code in (401, 403):
            raise PermissionError(f"HTTP {r.status_code}")
        r.raise_for_status()
        data = r.json()
    if not isinstance(data, dict):
        return None
    matches = data.get("matches")
    if not isinstance(matches, list) or not matches:
        return None
    m = matches[0]
    if not isinstance(m, dict):
        return None
    eid = m.get("episodeId")
    if eid in (None, "", 0, "0"):
        return None
    return {"episode_id": int(eid), "anime": m.get("animeTitle") or "",
            "episode": m.get("episodeTitle") or "",
            "year": m.get("typeDescription") or ""}


async def _search_episodes(base: str, title: str, episode: int, timeout: float = 10.0) -> int | None:
    params = {"anime": title}
    if episode:
        params["episode"] = str(episode)
    async with _client(timeout) as cli:
        r = await cli.get(f"{base}/api/v2/search/episodes", params=params)
        if r.status_code in (401, 403):
            raise PermissionError(f"HTTP {r.status_code}")
        r.raise_for_status()
        data = r.json()
    animes = (data or {}).get("animes") if isinstance(data, dict) else None
    if not isinstance(animes, list):
        return None
    for a in animes:
        eps = a.get("episodes") if isinstance(a, dict) else None
        if isinstance(eps, list):
            for ep in eps:
                eid = (ep or {}).get("episodeId")
                if eid not in (None, "", 0, "0"):
                    return int(eid)
    return None


async def _comments(base: str, episode_id: int, timeout: float = 15.0) -> list:
    async with _client(timeout) as cli:
        r = await cli.get(f"{base}/api/v2/comment/{episode_id}",
                          params={"format": "json", "duration": "true"})
        r.raise_for_status()
        data = r.json()
    if isinstance(data, dict) and isinstance(data.get("data"), dict) \
            and "comments" not in data:
        data = data["data"]
    items = (data or {}).get("comments") if isinstance(data, dict) else None
    return items if isinstance(items, list) else []


def _match_names(title: str, season: int, episode: int, year: str, ep_title: str) -> list[str]:
    if not title:
        return []
    if episode:
        names = [f"{title} S{season or 1:02d}E{episode:02d}"]
        if ep_title:
            names.append(f"{title} {ep_title}")
        names.append(f"{title} 第{episode}集")
        if year:
            names.append(f"{title} {year} S{season or 1:02d}E{episode:02d}")
    else:
        names = [title]
        if year:
            names.append(f"{title} {year}")
    return list(dict.fromkeys(names))


async def _match_cached(base: str, title: str, season: int, episode: int,
                        year: str, ep_title: str) -> int | None:
    key = f"{base}|{title}|{season}|{episode}|{year}"
    hit = _MATCH.get(key)
    now = time.time()
    if hit:
        ts, eid = hit
        if now - ts < (_TTL if eid else _NEG_TTL):
            return eid
    eid = None
    last_exc: Exception | None = None
    for name in _match_names(title, season, episode, year, ep_title):
        try:
            m = await _match(base, name)
        except Exception as exc:  # 网络/Token 错误：稍后重试，不要缓存太久
            last_exc = exc
            break
        if m:
            eid = m["episode_id"]
            break
    if eid is None and episode and last_exc is None:
        try:
            eid = await _search_episodes(base, title, episode)
        except Exception:
            eid = None
    _MATCH[key] = (now, eid)
    if len(_MATCH) > _MAX_CACHE:
        for k in list(_MATCH)[: _MAX_CACHE // 2]:
            _MATCH.pop(k, None)
    return eid


async def _resolve_identity(entry: dict) -> dict:
    mg = entry.get("mg") or ""
    og = entry.get("og") or ""
    title = entry.get("title") or ""
    year = entry.get("year") or ""
    cat = entry.get("cat") or "tv"
    season, episode, ep_title = 0, 0, entry.get("ep_title") or ""
    dur = int(entry.get("dur") or 0)

    target = store.resolve_media_guid(mg) if mg else None
    if target is None and mg and time.time() - float(entry.get("at") or 0) < 120:
        # 榜单片刚点开时后台还在搜源：最多等 4 秒，等 store 完成绑定
        for _ in range(20):
            await asyncio.sleep(0.2)
            target = store.resolve_media_guid(mg)
            if target is not None:
                break
    if target:
        og = target.get("online_guid") or og
        title = target.get("title") or title
        brief = store.get_title_by_guid(og) or {}
        year = str(brief.get("year") or year or "")
        if target.get("kind") == "episode" or target.get("ep_guid"):
            season = int(target.get("season") or 1)
            episode = int(target.get("index", 0) or 0) + 1
            ep_title = target.get("ep_title") or ep_title
        elif brief and inject.is_tv(brief):
            season = 1
            episode = int(target.get("index", 0) or 0) + 1
            ep_title = target.get("ep_title") or ep_title
        else:
            season, episode = 0, 0
    elif cat == "movie":
        season, episode = 0, 0
    elif episode <= 0:
        season, episode = 1, 1

    return {"title": title, "year": year, "season": season,
            "episode": episode, "ep_title": ep_title, "duration": dur}


async def _generate(entry: dict) -> str:
    base = api_base()
    if not base:
        return ""
    ident = await _resolve_identity(entry)
    if not ident["title"]:
        return ""
    eid = await _match_cached(base, ident["title"], ident["season"],
                              ident["episode"], ident["year"], ident["ep_title"])
    if not eid:
        return ""
    comments = await _comments(base, eid)
    cfg = config.get()
    return _build_ass(comments,
                      offset=float(cfg.get("danmu_offset") or 0),
                      limit=int(cfg.get("danmu_limit") or 800),
                      duration=ident.get("duration") or 0)


async def ass_for(guid: str) -> str:
    """按字幕 guid 生成 ASS 文本；任何异常都降级为空字幕，不影响播放。"""
    entry = _BIND.get(guid)
    if not entry:
        return ""
    now = time.time()
    hit = _ASS.get(guid)
    if hit:
        ts, text = hit
        if now - ts < (_TTL if text else _NEG_TTL):
            return text
    async with _LOCK:
        hit = _ASS.get(guid)
        if hit:
            ts, text = hit
            if now - ts < (_TTL if text else _NEG_TTL):
                return text
        try:
            text = await _generate(entry)
        except Exception:
            text = ""
        _ASS[guid] = (time.time(), text)
        if len(_ASS) > _MAX_CACHE:
            for k in list(_ASS)[: _MAX_CACHE // 2]:
                _ASS.pop(k, None)
        return text


async def test(api: str, token: str) -> dict:
    base = api_base(api, token)
    if not base:
        return {"ok": False, "msg": "请填写弹幕接口地址"}
    started = time.time()
    try:
        async with _client(8.0) as cli:
            r = await cli.get(f"{base}/api/v2/search/anime", params={"keyword": "测试"})
        ms = int((time.time() - started) * 1000)
        if r.status_code in (401, 403):
            return {"ok": False, "ms": ms,
                    "msg": f"HTTP {r.status_code}：Token 可能不正确"}
        if r.status_code >= 400:
            return {"ok": False, "ms": ms, "msg": f"HTTP {r.status_code}"}
        data = r.json()
        n = len(data.get("animes") or []) if isinstance(data, dict) else 0
        return {"ok": True, "ms": ms, "count": n,
                "msg": f"连接正常（{ms} ms，搜索返回 {n} 条）"}
    except Exception as exc:
        ms = int((time.time() - started) * 1000)
        return {"ok": False, "ms": ms,
                "msg": f"连接失败：{type(exc).__name__}: {exc}"}
